TEST(InflateTest, Zlib)
{
    EXPECT_EQ(AsString(InflateZlib(Base64Decode("eJyryslMUihIrMzJT0wBAB7KBLw="))), "zlib payload");
    EXPECT_THROW(InflateZlib(std::vector<uint8_t>{0x00, 0x00}), ParseError);
}

TEST(InflateTest, CorruptInput)
{
    EXPECT_THROW(Inflate(std::vector<uint8_t>{}), ParseError);
    EXPECT_THROW(Inflate(std::vector<uint8_t>{0x07}), ParseError);                              // block type 3
    EXPECT_THROW(Inflate(std::vector<uint8_t>{0x01, 0x05, 0x00, 0x00, 0x00, 'x'}), ParseError); // bad NLEN
    EXPECT_THROW(Inflate(Base64Decode("y0jNyclXyEAiy/OLclIA"), 5), ParseError);                 // size limit
}
