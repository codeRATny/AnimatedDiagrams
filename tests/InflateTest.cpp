#include <gtest/gtest.h>

#include <numeric>

#include "Common/Exceptions.hpp"
#include "Import/Inflate.hpp"
#include "Utils/Text.hpp"

using namespace ad;

namespace
{

std::string AsString(const std::vector<uint8_t> &v) { return {v.begin(), v.end()}; }

} // namespace

TEST(InflateTest, StoredBlock)
{
    // BFINAL=1, BTYPE=00, LEN=5, NLEN=~5, "hello"
    const std::vector<uint8_t> data{0x01, 0x05, 0x00, 0xFA, 0xFF, 'h', 'e', 'l', 'l', 'o'};
    EXPECT_EQ(AsString(Inflate(data)), "hello");
}

TEST(InflateTest, FixedHuffman)
{
    // zlib.compressobj(9, DEFLATED, -15) of "hello hello hello world"
    EXPECT_EQ(AsString(Inflate(Base64Decode("y0jNyclXyEAiy/OLclIA"))), "hello hello hello world");
}

